create table if not exists public.jarvis_commands (
 id uuid primary key, device_id text not null, command text not null, args jsonb not null default '{}'::jsonb,
 status text not null default 'queued', created_at timestamptz not null default now(), sent_at timestamptz
);
create table if not exists public.jarvis_command_results (
 id bigint generated by default as identity primary key, command_id uuid, device_id text not null,
 ok boolean not null default false, result jsonb not null default '{}'::jsonb, created_at timestamptz not null default now()
);
create table if not exists public.jarvis_memories (
 id bigint generated by default as identity primary key, category text not null default 'general', content text not null,
 importance double precision not null default 0.5, metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now()
);
create table if not exists public.jarvis_routines (
 id bigint generated by default as identity primary key, name text not null, enabled boolean not null default true,
 cron text not null, timezone text not null default 'America/Sao_Paulo', actions jsonb not null default '[]'::jsonb, created_at timestamptz not null default now()
);
alter table public.jarvis_commands enable row level security;
